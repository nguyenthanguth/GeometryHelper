def _yaml(uid: str, kind: str, members: list[tuple[str, str, str | None]]) -> str:
    """The ``.yml`` file docfx's metadata step writes for one type: the type, then its members."""
    name = uid.rsplit(".", 1)[1]
    lines = ["### YamlMime:ManagedReference", "items:", f"- uid: {uid}", f"  commentId: T:{uid}", f"  id: {name}"]
    if members:
        lines += ["  children:"] + [f"  - {uid}.{suffix}" for suffix, _, _ in members]
    lines += [f"  type: {kind}"]
    for suffix, member_kind, group in members:
        lines += [f"- uid: {uid}.{suffix}", f"  id: {suffix}", f"  type: {member_kind}"]
        if group is not None:
            lines += [f"  overload: {uid}.{group}"]
    return "\n".join(lines) + "\n"


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


ApiTypes = dict[str, tuple[str, list[tuple[str, str, str | None]]]]


def _inputs(base: Path, geometry: str = GEOMETRY_PYI, api: ApiTypes | None = None) -> tuple[Path, Path]:
    """Writes the tiny stubs and api folders under ``base`` and gives their paths."""
    stubs, api_folder = base / "GeometryHelper-stubs", base / "api"
    _write(stubs / "Geometry" / "__init__.pyi", geometry)
    _write(stubs / "Enums" / "__init__.pyi", ENUMS_PYI)
    for uid, (kind, members) in (API if api is None else api).items():
        _write(api_folder / f"{uid}.yml", _yaml(uid, kind, members))
    return stubs, api_folder


def _generate(stubs: Path, api: Path, out: Path, *extra: str) -> "subprocess.CompletedProcess[str]":
    assert GENERATOR.is_file(), f"{GENERATOR} does not exist: the generator is not written"
    return subprocess.run(
        [sys.executable, "-I", str(GENERATOR), "--stubs", str(stubs), "--api", str(api), "--out", str(out), *extra],
        capture_output=True,
        text=True,
        timeout=120,
        cwd=ROOT,
    )


