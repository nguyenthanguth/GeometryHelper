# ---- the same bytes on a rerun, a clean folder, the inputs untouched -----------------------------------------------


def _tree(folder: Path) -> dict[str, str]:
    return {
        p.relative_to(folder).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(folder.rglob("*"))
        if p.is_file()
    }


def test_a_rerun_gives_the_same_bytes_and_removes_what_the_first_run_left_that_it_no_longer_writes(
    tmp_path: Path,
) -> None:
    stubs, api = _inputs(tmp_path)
    out = tmp_path / "python-api"
    _generate(stubs, api, out)
    first = _tree(out)
    (out / "stale.md").write_bytes(b"left by an older run\n")
    (out / GEOMETRY / "Gone.md").write_bytes(b"a type that is no more\n")
    (out / "old-folder").mkdir()
    (out / "old-folder" / "x.md").write_bytes(b"x\n")

    process = _generate(stubs, api, out)

    assert process.returncode == 0, process.stderr
    assert _tree(out) == first


def test_the_stubs_and_the_api_files_are_left_as_they_were(tmp_path: Path) -> None:
    stubs, api = _inputs(tmp_path)
    before = (_tree(stubs), _tree(api))

    process = _generate(stubs, api, tmp_path / "out")

    assert process.returncode == 0, process.stderr
    assert (_tree(stubs), _tree(api)) == before
    assert sorted(p.name for p in tmp_path.iterdir()) == ["GeometryHelper-stubs", "api", "out"]


def test_the_order_of_the_files_in_the_folders_does_not_change_a_byte(tmp_path: Path) -> None:
    # The same inputs written in the opposite order of their files (the namespaces and the api files), the same pages.
    first_stubs, first_api = _inputs(tmp_path / "a")
    second = tmp_path / "b"
    stubs, api_folder = second / "GeometryHelper-stubs", second / "api"
    _write(stubs / "Enums" / "__init__.pyi", ENUMS_PYI)
    _write(stubs / "Geometry" / "__init__.pyi", GEOMETRY_PYI)
    for uid, (kind, members) in reversed(list(API.items())):
        _write(api_folder / f"{uid}.yml", _yaml(uid, kind, members))

    _generate(first_stubs, first_api, tmp_path / "out-a")
    _generate(stubs, api_folder, tmp_path / "out-b")

    assert _tree(tmp_path / "out-a") == _tree(tmp_path / "out-b")
