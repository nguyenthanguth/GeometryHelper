# ---- a page read back ---------------------------------------------------------------------------------------------


def _unescape(text: str) -> str:
    return re.sub(r"\\(.)", r"\1", text)


def _sections(page: str) -> tuple[list[str], dict[str, list[dict[str, object]]]]:
    """The lines before the first ``##``, and the sections by name, each a list of member groups.

    A group is ``{"name", "link", "blocks"}``: the ``###`` heading unescaped, the uid of its ``[.NET](xref:...)`` line
    (None for none), and its blocks, each ``{"code", "text"}``: a fenced ``python`` block and the lines after it up to
    the next.
    """
    preamble: list[str] = []
    sections: dict[str, list[dict[str, object]]] = {}
    group: dict[str, object] | None = None
    block: dict[str, str] | None = None
    in_code = False
    for line in page.split("\n"):
        if in_code:
            if line == "```":
                in_code = False
            else:
                assert block is not None
                block["code"] += ("\n" if block["code"] else "") + line
        elif line.startswith("## "):
            sections[line[3:]] = []
            group = block = None
        elif line.startswith("### "):
            assert sections, "a group outside a section"
            group = {"name": _unescape(line[4:]), "link": None, "blocks": []}
            sections[list(sections)[-1]].append(group)
            block = None
        elif group is None:
            preamble.append(line)
        elif line == "```python":
            block = {"code": "", "text": ""}
            blocks = group["blocks"]
            assert isinstance(blocks, list)
            blocks.append(block)
            in_code = True
        elif (link := re.fullmatch(r"\[\.NET\]\(xref:(.+)\)", line)) and block is None:
            group["link"] = link.group(1)
        elif line.strip() and block is not None:
            block["text"] += ("\n" if block["text"] else "") + line
    return preamble, sections


def _groups(out: Path, namespace: str, name: str, section: str) -> list[dict[str, object]]:
    return _sections(_page(out, namespace, name))[1][section]


def _blocks(group: dict[str, object]) -> list[dict[str, str]]:
    blocks = group["blocks"]
    assert isinstance(blocks, list)
    return blocks


def _cells(row: str) -> list[str]:
    """The cells of a table row, split at the pipes that are not escaped."""
    return [cell.strip() for cell in re.split(r"(?<!\\)\|", row.strip())[1:-1]]


def _table(text: str, header: list[str]) -> list[list[str]]:
    """The rows under the table whose header cells are ``header`` (the separator row skipped)."""
    lines = text.split("\n")
    start = next(n for n, line in enumerate(lines) if line.startswith("|") and _cells(line) == header)
    rows = []
    for line in lines[start + 2 :]:
        if not line.startswith("|"):
            break
        rows.append(_cells(line))
    assert re.fullmatch(r"\|?(\s*:?-+:?\s*\|)+", lines[start + 1].strip()), "the row under the header is no separator"
    return rows


