"""D1: the page generator ``tools/python/make-api-pages.py`` (P5 D1003, D1004), run as a subprocess on a tiny stub
folder and a tiny ``api`` folder made here, in the shapes the real ones have.

The stubs are what ``tools/GeometryHelper.PyStubs`` writes (an ``__init__.pyi`` for each namespace under the folder of
the stubs, the root one being the namespace ``GeometryHelper``); the api folder holds, for each type, the YAML docfx's
metadata step writes: an item for the type with its ``type:`` (``Struct``, ``Interface``, as docfx capitalises it), an
item for each member with ``type:``, and ``overload: <group uid>*`` for the members that have a group. A member the
tests leave out of the YAML (``Hidden``, ``Side.Right``, ``__hash__``, ``__int__``) is one the .NET reference has no
page for, so its group has no link.

The namespace ``GeometryHelper.Geometry`` holds ``Point`` (a struct, with every kind of member), ``Zed`` (no member),
``IShape`` (an interface the stubs write as a class of ``System.Object``); ``GeometryHelper.Enums`` holds ``Side``.
Counts the stub gives: 4 types; 16 member groups of ``Point`` (14 linked), 1 of ``IShape`` (linked), 3 of ``Side`` (1
linked): 20 groups, 16 linked, 4 not.

Where D1004 leaves a detail open the tests accept both readings: the heading of a group is the name or the name with
its underscores escaped; the link of a type in a table is its page or its uid; the order of the rows of a namespace
page is not pinned (the toc's is).
"""

