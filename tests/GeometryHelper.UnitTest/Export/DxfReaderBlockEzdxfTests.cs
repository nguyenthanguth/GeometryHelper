        private static GeoPoint3 P(double x, double y, double z) => new GeoPoint3(x, y, z);

        private static GeoPoint3 Lift(GeoPoint2 p) => new GeoPoint3(p.X, p.Y, 0.0);

        private static void Same(GeoPoint3 expected, GeoPoint3 actual, string what)
            => Assert.True(expected.DistanceTo(actual) <= Near * Math.Max(1.0, expected.DistanceTo(GeoPoint3.Origin)), what + ": ezdxf has " + expected + ", read " + actual);

        private static void SameEnds(GeoPoint3 first, GeoPoint3 last, GeoPoint3 start, GeoPoint3 end, string what)
        {
            if (first.DistanceTo(start) <= first.DistanceTo(end))
            {
                Same(first, start, what + ", start");
                Same(last, end, what + ", end");
            }
            else
            {
                Same(first, end, what + ", start of the reversed");
                Same(last, start, what + ", end of the reversed");
            }
        }

        private static void Parallel(GeoVector3 expected, GeoVector3 actual, string what)
            => Assert.True(expected.Normalize().CrossProduct(actual.Normalize()).Length <= Near, what + ": ezdxf has the normal " + expected + ", read " + actual);

        /// <summary>A shape of the reading, as ezdxf would have it checked: points of space, of the plane on the floor.</summary>
        private abstract class Ez
        {
            internal abstract void Check(object shape, string what);

            internal static Ez Line(GeoPoint3 start, GeoPoint3 end) => new EzLine { Start = start, End = end };

            internal static Ez Point(GeoPoint3 at) => new EzPoint { At = at };

            internal static Ez Circle(GeoPoint3 centre, double radius, GeoPoint3 extrusion) => new EzCircle { Centre = centre, Radius = radius, Normal = extrusion.ToVector() };

            internal static Ez Arc(GeoPoint3 centre, double radius, GeoPoint3 extrusion, GeoPoint3 start, GeoPoint3 middle, GeoPoint3 end)
                => new EzArc { Centre = centre, Radius = radius, Normal = extrusion.ToVector(), Start = start, Middle = middle, End = end };

            internal static Ez Ellipse(GeoPoint3 centre, GeoPoint3 major, double ratio, GeoPoint3 extrusion, bool whole, params GeoPoint3[] points)
                => new EzEllipse { Centre = centre, Major = major.ToVector(), Ratio = ratio, Normal = extrusion.ToVector().Normalize(), Whole = whole, Points = points };

            internal static Ez Polyline(bool closed, GeoPoint3[] vertices, GeoPoint3[] middles) => new EzPolyline { Closed = closed, Vertices = vertices, Middles = middles };

            internal static Ez Spline(GeoPoint3[] points, double[] weights) => new EzSpline { Points = points, Weights = weights };

            internal static Ez Face(params GeoPoint3[] corners) => new EzFace { Corners = corners };
        }

        private sealed class EzLine : Ez
        {
            internal GeoPoint3 Start;
            internal GeoPoint3 End;

            internal override void Check(object shape, string what)
            {
                GeoLine3 line = shape is GeoLine2 flat ? new GeoLine3(Lift(flat.StartPoint), Lift(flat.EndPoint)) : Assert.IsType<GeoLine3>(shape);
                Same(Start, line.StartPoint, what + ", start");
                Same(End, line.EndPoint, what + ", end");
            }
        }

        private sealed class EzPoint : Ez
        {
            internal GeoPoint3 At;

            internal override void Check(object shape, string what) => Same(At, shape is GeoPoint2 flat ? Lift(flat) : Assert.IsType<GeoPoint3>(shape), what);
        }

        private sealed class EzCircle : Ez
        {
            internal GeoPoint3 Centre;
            internal double Radius;
            internal GeoVector3 Normal;

            internal override void Check(object shape, string what)
            {
                GeoCircle3 circle = shape is GeoCircle2 flat ? new GeoCircle3(Lift(flat.Center), GeoVector3.ZAxis, flat.Radius) : Assert.IsType<GeoCircle3>(shape);
                Same(Centre, circle.Center, what + ", centre");
                Assert.True(Math.Abs(Radius - circle.Radius) <= Near * Radius, what + ": radius " + circle.Radius + " where ezdxf has " + Radius);
                Parallel(Normal, circle.Normal, what);
            }
        }

        private sealed class EzArc : Ez
        {
            internal GeoPoint3 Centre;
            internal double Radius;
            internal GeoVector3 Normal;
            internal GeoPoint3 Start;
            internal GeoPoint3 Middle;
            internal GeoPoint3 End;

            internal override void Check(object shape, string what)
            {
                GeoPoint3 centre, start, middle, end;
                double radius;

                if (shape is GeoArc2 flat)
                {
                    centre = Lift(flat.Center);
                    start = Lift(flat.StartPoint);
                    middle = Lift(flat.GetPointAtParameter(0.5));
                    end = Lift(flat.EndPoint);
                    radius = flat.Radius;
                    Parallel(Normal, GeoVector3.ZAxis, what);
                }
                else
                {
                    GeoArc3 arc = Assert.IsType<GeoArc3>(shape);
                    centre = arc.Center;
                    start = arc.StartPoint;
                    middle = arc.GetPointAtParameter(0.5);
                    end = arc.EndPoint;
                    radius = arc.Radius;
                    Parallel(Normal, arc.Normal, what);
                }

                Same(Centre, centre, what + ", centre");
                Assert.True(Math.Abs(Radius - radius) <= Near * Radius, what + ": radius " + radius + " where ezdxf has " + Radius);
                SameEnds(Start, End, start, end, what);
                Same(Middle, middle, what + ", middle");
            }
        }

        private sealed class EzEllipse : Ez
        {
            internal GeoPoint3 Centre;
            internal GeoVector3 Major;
            internal double Ratio;
            internal GeoVector3 Normal;
            internal bool Whole;
            internal GeoPoint3[] Points;

            /// <summary>How far a point stands off ezdxf's ellipse, in its plane and out of it, read by its own axes.</summary>
            private double Off(GeoPoint3 p)
            {
                GeoVector3 minor = Normal.CrossProduct(Major).Normalize().Multiply(Major.Length * Ratio);
                GeoVector3 d = Centre.GetVectorTo(p);
                double x = d.DotProduct(Major) / Major.LengthSquared;
                double y = d.DotProduct(minor) / minor.LengthSquared;
                return Math.Abs(Math.Sqrt(x * x + y * y) - 1.0) * Major.Length + Math.Abs(d.DotProduct(Normal));
            }

            internal override void Check(object shape, string what)
            {
                Func<double, GeoPoint3> at;

                if (Whole)
                {
                    GeoEllipse3 ellipse = shape is GeoEllipse2 flat
                        ? new GeoEllipse3(Lift(flat.Center), GeoVector3.ZAxis, new GeoVector3(flat.MajorAxis.X, flat.MajorAxis.Y, 0.0), flat.MajorRadius, flat.MinorRadius)
                        : Assert.IsType<GeoEllipse3>(shape);

                    Same(Centre, ellipse.Center, what + ", centre");
                    Assert.True(Math.Abs(Major.Length - ellipse.MajorRadius) <= Near * ellipse.MajorRadius, what + ": major radius " + ellipse.MajorRadius + " where ezdxf has " + Major.Length);
                    Assert.True(Math.Abs(Major.Length * Ratio - ellipse.MinorRadius) <= Near * ellipse.MajorRadius, what + ": minor radius " + ellipse.MinorRadius + " where ezdxf has " + Major.Length * Ratio);
                    at = t => ellipse.GetPointAtParameter(t);
                }
                else
                {
                    if (shape is GeoSpline2 flat)
                    {
                        at = t => Lift(flat.GetPointAtParameter(t));
                    }
                    else
                    {
                        GeoSpline3 spline = Assert.IsType<GeoSpline3>(shape);
                        at = t => spline.GetPointAtParameter(t);
                    }

                    SameEnds(Points[0], Points[4], at(0.0), at(1.0), what);

                    // The middle of ezdxf's part is on the spline: so it is that part, not the rest of the ellipse.
                    double nearest = Enumerable.Range(0, 2001).Min(k => Points[2].DistanceTo(at(k / 2000.0)));
                    double step = 1.0 / 2000.0;
                    int best = Enumerable.Range(0, 2001).OrderBy(k => Points[2].DistanceTo(at(k / 2000.0))).First();
                    double lo = Math.Max(0.0, (best - 1) * step);
                    double hi = Math.Min(1.0, (best + 1) * step);

                    for (int i = 0; i < 200; i++)
                    {
                        double a = lo + (hi - lo) / 3.0;
                        double b = hi - (hi - lo) / 3.0;

                        if (Points[2].DistanceTo(at(a)) < Points[2].DistanceTo(at(b)))
                        {
                            hi = b;
                        }
                        else
                        {
                            lo = a;
                        }
                    }

                    Assert.True(Points[2].DistanceTo(at((lo + hi) * 0.5)) <= 1E-7 && nearest < 1.0, what + ": the middle of ezdxf's part, " + Points[2] + ", is " + Points[2].DistanceTo(at((lo + hi) * 0.5)) + " off the spline");
                }

                // Every point read is on ezdxf's ellipse.
                for (int k = 0; k <= 32; k++)
                {
                    GeoPoint3 p = at(k / 32.0);
                    Assert.True(Off(p) <= Near * Major.Length, what + ": the point " + p + " at " + k + "/32 is " + Off(p) + " off ezdxf's ellipse");
                }

                foreach (GeoPoint3 p in Points)
                {
                    Assert.True(Off(p) <= Near * Major.Length, what + ": ezdxf's own point " + p + " is off its ellipse by " + Off(p));
                }
            }
        }

        private sealed class EzPolyline : Ez
        {
            internal bool Closed;
            internal GeoPoint3[] Vertices;
            internal GeoPoint3[] Middles;

            internal override void Check(object shape, string what)
            {
                GeoPoint3[] vertices;
                GeoPoint3[] middles;

                switch (shape)
                {
                    case GeoPolygonArc2 loop:
                        vertices = loop.Vertices.Select(Lift).ToArray();
                        middles = loop.GetEdges().Select(e => Lift(e.MidPoint)).ToArray();
                        Assert.True(Closed, what);
                        break;
                    case GeoPolylineArc2 chain:
                        vertices = chain.Vertices.Select(Lift).ToArray();
                        middles = chain.GetEdges().Select(e => Lift(e.MidPoint)).ToArray();
                        break;
                    case GeoPolygonArc3 loop:
                        vertices = loop.Vertices.ToArray();
                        middles = loop.GetEdges().Select(e => e.MidPoint).ToArray();
                        Assert.True(Closed, what);
                        break;
                    default:
                        GeoPolylineArc3 chain3 = Assert.IsType<GeoPolylineArc3>(shape);
                        vertices = chain3.Vertices.ToArray();
                        middles = chain3.GetEdges().Select(e => e.MidPoint).ToArray();
                        break;
                }

                Assert.Equal(Vertices.Length, vertices.Length);
                Assert.Equal(Middles.Length, middles.Length);

                for (int i = 0; i < Vertices.Length; i++)
                {
                    Same(Vertices[i], vertices[i], what + ", vertex " + i);
                }

                for (int i = 0; i < Middles.Length; i++)
                {
                    Same(Middles[i], middles[i], what + ", middle of edge " + i);
                }
            }
        }

        private sealed class EzSpline : Ez
        {
            internal GeoPoint3[] Points;
            internal double[] Weights;

            internal override void Check(object shape, string what)
            {
                GeoPoint3[] points;
                IReadOnlyList<double> weights;

                if (shape is GeoSpline2 flat)
                {
                    points = flat.ControlPoints.Select(Lift).ToArray();
                    weights = flat.IsRational ? flat.Weights : null;
                }
                else
                {
                    GeoSpline3 spline = Assert.IsType<GeoSpline3>(shape);
                    points = spline.ControlPoints.ToArray();
                    weights = spline.IsRational ? spline.Weights : null;
                }

                Assert.Equal(Points.Length, points.Length);

                for (int i = 0; i < points.Length; i++)
                {
                    Same(Points[i], points[i], what + ", control point " + i);
                }

                if (Weights.Length > 0)
                {
                    Assert.Equal(Weights, weights.ToArray());
                }
            }
        }

        private sealed class EzFace : Ez
        {
            internal GeoPoint3[] Corners;

            internal override void Check(object shape, string what)
            {
                GeoFace3 face = Assert.IsType<GeoFace3>(shape);
                IReadOnlyList<GeoPoint3> corners = face.Boundary.Vertices;

                Assert.Equal(Corners.Length, corners.Count);

                foreach (GeoPoint3 corner in Corners)
                {
                    Assert.True(corners.Min(c => c.DistanceTo(corner)) <= Near * Math.Max(1.0, corner.DistanceTo(GeoPoint3.Origin)), what + ": ezdxf's corner " + corner + " is not a corner of the face read");
                }
            }
        }
