        /// <summary>
        /// The top face beside the top notch: its first corner is 0.04 mm below the other three.
        /// </summary>
        private const string TopBesideTheNotch =
            "31693.2387323195 -26134.768136094652 5999.9622326742374 48223.422337105651 -26134.768136094648 6000 " +
            "48223.422337105651 -25734.768136094648 6000 31693.2387323195 -25734.768136094648 6000";

        /// <summary>
        /// Where the reference line of the beam starts: at the middle of its width, on its top.
        /// </summary>
        private static readonly GeoPoint3 Start = new GeoPoint3(18223.422337105654, -25934.768136094648, 6000.0);

        [Fact]
        public void AFaceTeklaLeftAHairOffFlatIsStillAFace()
        {
            GeoPolygon3 top = Loop(TopBesideTheNotch);

            Assert.True(top.Normal.IsCodirectionalTo(GeoVector3.ZAxis));
            Assert.InRange(top.Area, 16530.18 * 400.0 * 0.99999, 16530.18 * 400.0 * 1.00001);
        }

        [Fact]
        public void TheNotchedBeamIsClosedWithTheVolumeOfItsConcrete()
        {
            var beam = new GeoSolid3(Faces());

            Assert.Equal(26, beam.Faces.Count);
            Assert.True(beam.IsClosed());

            // 30 m of 3000 x 400, less two notches and three openings, each 600 x 800 through the 400.
            double concrete = 30000.0 * 3000.0 * 400.0 - 5 * 600.0 * 800.0 * 400.0;
            Assert.InRange(beam.Volume, concrete * 0.99999, concrete * 1.00001);
        }

        [Fact]
        public void APlaneAlongTheBeamGivesItsSection()
        {
            var beam = new GeoSolid3(Faces());

            // Upright through the reference line: the web, the two notches in its outline and the three openings as
            // its holes.
            GeoFace3 cut = Assert.Single(beam.Section(new GeoPlane3(Start, GeoVector3.YAxis)));

            Assert.Equal(3, cut.Holes.Count);
            double web = 30000.0 * 3000.0 - 5 * 600.0 * 800.0;
            Assert.InRange(cut.Area, web * 0.99999, web * 1.00001);
        }

        private static List<GeoFace3> Faces()
        {
            var faces = new List<GeoFace3>();

            foreach (string line in NotchedBeam.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries))
            {
                if (line.Trim().Length == 0)
                {
                    continue;
                }

                GeoPolygon3[] loops = line.Split('|').Select(Loop).ToArray();
                faces.Add(new GeoFace3(loops[0], loops.Skip(1)));
            }

            return faces;
        }

        private static GeoPolygon3 Loop(string coordinates)
        {
            double[] values = coordinates
                .Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(value => double.Parse(value, CultureInfo.InvariantCulture))
                .ToArray();
            var corners = new List<GeoPoint3>();

            for (int i = 0; i < values.Length; i += 3)
            {
                corners.Add(new GeoPoint3(values[i], values[i + 1], values[i + 2]));
            }

            return new GeoPolygon3(corners);
        }
