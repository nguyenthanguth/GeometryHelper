        private static readonly Lazy<StubRun> Run = new Lazy<StubRun>(() => StubRun.OfTheFixture());

        private static string Fixture => Run.Value.Module("Fixture");

        private static string Lines(params string[] lines) => string.Join("\n", lines) + "\n";

        [Fact]
        public void TheFixtureAssembly_GivesOneModuleForEachNamespace_AndCountsItsTypes()
        {
            StubReport report = Run.Value.Report;

            Assert.Equal(new[] { "GeometryHelper.Fixture", "GeometryHelper.Fixture.Other" }, report.Modules);
            AssemblyStubs assembly = Assert.Single(report.Assemblies);
            Assert.Equal("GeometryHelper.Fixture", assembly.Name);
            Assert.Equal(29, assembly.Types);
            Assert.Equal(2, assembly.Modules);
        }

        [Fact]
        public void EveryModule_StartsWithTheGeneratedLine_AndHasLineFeedsOnly()
        {
            foreach ((string relative, byte[] bytes) in Run.Value.Files())
            {
                string text = System.Text.Encoding.UTF8.GetString(bytes);

                Assert.StartsWith(
                    "# Generated by tools/GeometryHelper.PyStubs from GeometryHelper.Fixture 13.",
                    text,
                    StringComparison.Ordinal
                );
                Assert.DoesNotContain('\r', text);
                Assert.NotEqual(0xEF, bytes[0]);
                Assert.EndsWith("\n", text, StringComparison.Ordinal);
                Assert.False(text.EndsWith("\n\n", StringComparison.Ordinal), relative);
            }
        }

        [Fact]
        public void Types_AreSortedByName_AndMembersInTheOrderOfTheStubs()
        {
            string[] classes = Fixture
                .Split('\n')
                .Where(l => l.StartsWith("class ", StringComparison.Ordinal))
                .Select(l => l.Substring(6, l.IndexOf('(') - 6))
                .ToArray();

            Assert.Equal(classes.OrderBy(c => c, StringComparer.Ordinal), classes);
            Assert.True(
                Fixture.IndexOf("    Field: int", StringComparison.Ordinal)
                    < Fixture.IndexOf("def __init__(self, count: int) -> None", StringComparison.Ordinal)
            );
            Assert.True(
                Fixture.IndexOf("def __init__(self, count: int) -> None", StringComparison.Ordinal)
                    < Fixture.IndexOf("def Count(self) -> int", StringComparison.Ordinal)
            );
            Assert.True(
                Fixture.IndexOf("def Count(self) -> int", StringComparison.Ordinal)
                    < Fixture.IndexOf("def __getitem__(self, index: int) -> int", StringComparison.Ordinal)
            );
            Assert.True(
                Fixture.IndexOf("def __getitem__(self, index: int) -> int", StringComparison.Ordinal)
                    < Fixture.IndexOf("def Changed(self)", StringComparison.Ordinal)
            );
            Assert.True(
                Fixture.IndexOf("def Changed(self)", StringComparison.Ordinal)
                    < Fixture.IndexOf("def Another(self", StringComparison.Ordinal)
            );
            Assert.True(
                Fixture.IndexOf("def Twice(x: int, y: int)", StringComparison.Ordinal)
                    < Fixture.IndexOf("class Mode(", StringComparison.Ordinal)
            );
        }

