using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;

namespace GeometryHelper.Dxf.Viewer
{
    /// <summary>The named lists of a filter in the file AutoCAD keeps them in, <c>filter.nfl</c>.</summary>
    public sealed partial class CadSelectionFilter
    {
        private const string NflHeader = "Filter.nfl  --  Do not edit this file.";
        private const string NflSyntaxError = "Syntax error in Named Filter List file.  Delete filter.nfl.";

        /// <summary>
        /// Writes the named lists as AutoCAD's FILTER keeps them in <c>filter.nfl</c>: the line "Filter.nfl  --  Do not edit this
        /// file.", then for each list <c>:ai_lisp|NAME</c> with its tests as the lists of an AutoLISP <c>ssget</c> filter
        /// (<c>(8 . "WALLS")</c>, <c>(-4 . "&gt;=")</c> with <c>(40 . 15.0)</c>, <c>(-4 . "&lt;NOT")</c>) and <c>:ai_str|NAME</c>
        /// with the lines as the dialog lists them, tab between the columns. <c>*unnamed</c> is not kept.
        /// </summary>
        /// <returns>The text, its lines ended by a line feed.</returns>
        public string ToNfl()
        {
            var text = new StringBuilder();
            text.Append(NflHeader).Append('\n');

            foreach (KeyValuePair<string, List<CadFilterLine>> list in _named)
            {
                text.Append(":ai_lisp|").Append(list.Key).Append('\n');

                foreach (CadFilterLine line in list.Value)
                {
                    foreach (string element in Elements(line))
                    {
                        text.Append(element).Append('\n');
                    }
                }

                text.Append(":ai_str|").Append(list.Key).Append('\n');

                foreach (CadFilterLine line in list.Value)
                {
                    text.Append(Columns(line)).Append('\n');
                }
            }

            return text.ToString();
        }

        /// <summary>
        /// Reads named lists from the text of a <c>filter.nfl</c> file, in place of the named lists held; a list that does not
        /// read leaves them all as they were.
        /// </summary>
        /// <param name="text">The text of the file.</param>
        /// <returns>Null where it was read, else "Syntax error in Named Filter List file.  Delete filter.nfl.", as AutoCAD says it.</returns>
        /// <exception cref="ArgumentNullException">Thrown when the text is null.</exception>
        public string LoadNfl(string text)
        {
            if (text == null)
            {
                throw new ArgumentNullException(nameof(text));
            }

            var read = new SortedDictionary<string, List<CadFilterLine>>(StringComparer.OrdinalIgnoreCase);

            try
            {
                string[] rows = text.Replace("\r", string.Empty).Split('\n');
                int at = 0;

                while (at < rows.Length && !rows[at].StartsWith(":", StringComparison.Ordinal))
                {
                    at++;
                }

                while (at < rows.Length)
                {
                    string head = rows[at++];

                    if (head.Length == 0)
                    {
                        continue;
                    }

                    const string LispMark = ":ai_lisp|";
                    const string StrMark = ":ai_str|";

                    if (!head.StartsWith(LispMark, StringComparison.Ordinal))
                    {
                        return NflSyntaxError;
                    }

                    string name = head.Substring(LispMark.Length);
                    var elements = new List<Element>();

                    while (at < rows.Length && !rows[at].StartsWith(":", StringComparison.Ordinal))
                    {
                        if (rows[at].Trim().Length > 0)
                        {
                            elements.Add(Element.Parse(rows[at]));
                        }

                        at++;
                    }

                    if (at >= rows.Length || rows[at] != StrMark + name)
                    {
                        return NflSyntaxError;
                    }

                    at++;
                    var columns = new List<string>();

                    while (at < rows.Length && !rows[at].StartsWith(":", StringComparison.Ordinal))
                    {
                        if (rows[at].Trim().Length > 0)
                        {
                            columns.Add(rows[at]);
                        }

                        at++;
                    }

                    read[name] = LinesFrom(columns, elements);
                }
            }
            catch (Exception exception)
                when (exception is FormatException
                    || exception is ArgumentException
                    || exception is InvalidOperationException
                    || exception is ArgumentOutOfRangeException
                )
            {
                return NflSyntaxError;
            }

            _named.Clear();

            foreach (KeyValuePair<string, List<CadFilterLine>> list in read)
            {
                _named[list.Key] = list.Value;
            }

            if (!_named.ContainsKey(CurrentName))
            {
                CurrentName = Unnamed;
            }

            return null;
        }

        /// <summary>
        /// Reads the named lists from <see cref="FilePath"/>, as AutoCAD's FILTER does each time it starts; nothing happens
        /// where no file is set or none is there.
        /// </summary>
        /// <returns>Null where it was read or there is none, else what AutoCAD says of a file that does not read.</returns>
        public string Reload()
        {
            if (FilePath == null || !File.Exists(FilePath))
            {
                return null;
            }

            try
            {
                return LoadNfl(File.ReadAllText(FilePath, Encoding.UTF8));
            }
            catch (Exception exception) when (exception is IOException || exception is UnauthorizedAccessException)
            {
                GeometryHelperLog.Warn(
                    "CadSelectionFilter: the named lists could not be read from " + FilePath + ".",
                    exception
                );
                return null;
            }
        }

        private static IEnumerable<string> Elements(CadFilterLine line)
        {
            CadFilterProperty property = line.Property;
            int code = CadFilterLine.CodeOf(property);

            if (CadFilterLine.IsGroup(property))
            {
                yield return "(-4 . \"" + CadFilterLine.GroupToken(property) + "\")";
                yield break;
            }

            if (CadFilterLine.TakesOperators(property) && !AllEqual(line.Operators))
            {
                yield return "(-4 . \"" + string.Join(",", line.Operators) + "\")";
            }

            if (property == CadFilterProperty.Object)
            {
                yield return "(0 . \"" + Quote(CadFilterEntities.DxfNameOf(line.Value)) + "\")";
            }
            else if (property == CadFilterProperty.XdataId)
            {
                yield return "(-3 (\"" + Quote(line.Value) + "\"))";
            }
            else if (property == CadFilterProperty.Transparency)
            {
                yield return "(440 . " + line.TransparencyValue.ToString(CultureInfo.InvariantCulture) + ")";
            }
            else if (property == CadFilterProperty.Color)
            {
                yield return "(62 . " + line.ColorIndex.ToString(CultureInfo.InvariantCulture) + ")";
            }
            else if (CadFilterLine.IsPoint(property))
            {
                var parts = new List<string>();

                foreach (double number in line.Numbers)
                {
                    parts.Add(Real(number));
                }

                yield return "(" + code.ToString(CultureInfo.InvariantCulture) + " " + string.Join(" ", parts) + ")";
            }
            else if (CadFilterLine.TakesOperators(property))
            {
                bool angle = property == CadFilterProperty.BlockRotation || property == CadFilterProperty.TextRotation;
                double number = angle ? line.Numbers[0] * Math.PI / 180.0 : line.Numbers[0];
                yield return "(" + code.ToString(CultureInfo.InvariantCulture) + " . " + Real(number) + ")";
            }
            else
            {
                yield return "(" + code.ToString(CultureInfo.InvariantCulture) + " . \"" + Quote(line.Value) + "\")";
            }
        }

        private static string Columns(CadFilterLine line)
        {
            if (CadFilterLine.IsGroup(line.Property))
            {
                return line.Name + "\t";
            }

            if (CadFilterLine.IsPoint(line.Property))
            {
                IReadOnlyList<double> n = line.Numbers;
                IReadOnlyList<string> o = line.Operators;
                return line.Name
                    + "\tX\t"
                    + o[0]
                    + "\t"
                    + CadFilterLine.Number(n[0])
                    + "\tY\t"
                    + o[1]
                    + "\t"
                    + CadFilterLine.Number(n[1])
                    + "\tZ\t"
                    + o[2]
                    + "\t"
                    + CadFilterLine.Number(n[2]);
            }

            return line.Name + "\t\t" + line.Operators[0] + "\t" + line.Value;
        }

        private static List<CadFilterLine> LinesFrom(List<string> columns, List<Element> elements)
        {
            var lines = new List<CadFilterLine>();
            int next = 0;

            Element Take()
            {
                if (next >= elements.Count)
                {
                    throw new FormatException("The tests end before the lines do.");
                }

                return elements[next++];
            }

            foreach (string row in columns)
            {
                string[] tokens = row.Split(new[] { '\t' }, StringSplitOptions.RemoveEmptyEntries);

                for (int i = 0; i < tokens.Length; i++)
                {
                    tokens[i] = tokens[i].Trim();
                }

                if (tokens.Length == 0 || !CadFilterLine.TryFind(tokens[0], out CadFilterProperty property))
                {
                    throw new FormatException("A line of no property.");
                }

                Element element = Take();
                string[] operators = Array.Empty<string>();

                if (CadFilterLine.IsGroup(property))
                {
                    lines.Add(new CadFilterLine(property, string.Empty));
                    continue;
                }

                if (element.Code == -4 && CadFilterLine.TakesOperators(property))
                {
                    operators = element.Text.Split(',');
                    element = Take();
                }

                string value;

                if (property == CadFilterProperty.Object)
                {
                    value = tokens[tokens.Length - 1];
                }
                else if (property == CadFilterProperty.Transparency)
                {
                    value = CadFilterLine.TransparencyFromValue((int)element.Numbers[0]);
                }
                else if (CadFilterLine.IsPoint(property))
                {
                    value = string.Join(
                        ",",
                        Array.ConvertAll(element.Numbers, n => n.ToString("R", CultureInfo.InvariantCulture))
                    );
                }
                else if (CadFilterLine.TakesOperators(property))
                {
                    bool angle =
                        property == CadFilterProperty.BlockRotation || property == CadFilterProperty.TextRotation;
                    double number = angle ? element.Numbers[0] * 180.0 / Math.PI : element.Numbers[0];
                    value = number.ToString("R", CultureInfo.InvariantCulture);
                }
                else
                {
                    value = element.Text;
                }

                lines.Add(new CadFilterLine(property, value, operators));
            }

            return lines;
        }

        private static bool AllEqual(IReadOnlyList<string> operators)
        {
            foreach (string op in operators)
            {
                if (op != "=")
                {
                    return false;
                }
            }

            return true;
        }

        private static string Real(double value)
        {
            string text = value.ToString("R", CultureInfo.InvariantCulture);
            return text.IndexOfAny(new[] { '.', 'E' }) < 0 ? text + ".0" : text;
        }

        private static string Quote(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

        // One list of the file's AutoLISP lines: its group code, then a text, or numbers.
        private sealed class Element
        {
            internal int Code { get; private set; }

            internal string Text { get; private set; }

            internal double[] Numbers { get; private set; } = Array.Empty<double>();

            internal static Element Parse(string row)
            {
                string text = row.Trim();

                if (text.Length < 4 || text[0] != '(' || text[text.Length - 1] != ')')
                {
                    throw new FormatException("Not a list.");
                }

                text = text.Substring(1, text.Length - 2).Trim();
                int space = text.IndexOf(' ');

                if (space < 0)
                {
                    throw new FormatException("A list with no value.");
                }

                var element = new Element
                {
                    Code = int.Parse(text.Substring(0, space), NumberStyles.Integer, CultureInfo.InvariantCulture),
                };
                string rest = text.Substring(space + 1).Trim();

                if (rest.StartsWith("(", StringComparison.Ordinal))
                {
                    element.Text = Unquote(rest.Substring(1).Trim());
                }
                else if (rest.StartsWith(".", StringComparison.Ordinal))
                {
                    rest = rest.Substring(1).Trim();

                    if (rest.StartsWith("\"", StringComparison.Ordinal))
                    {
                        element.Text = Unquote(rest);
                    }
                    else
                    {
                        element.Numbers = new[]
                        {
                            double.Parse(rest, NumberStyles.Float, CultureInfo.InvariantCulture),
                        };
                    }
                }
                else
                {
                    string[] parts = rest.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
                    element.Numbers = Array.ConvertAll(parts, p =>
                        double.Parse(p, NumberStyles.Float, CultureInfo.InvariantCulture)
                    );
                }

                if (element.Text == null && element.Numbers.Length == 0)
                {
                    throw new FormatException("A list with no value.");
                }

                return element;
            }

            private static string Unquote(string text)
            {
                if (text.Length < 2 || text[0] != '"')
                {
                    throw new FormatException("A text without its quotes.");
                }

                var result = new StringBuilder();

                for (int i = 1; i < text.Length; i++)
                {
                    char c = text[i];

                    if (c == '\\' && i + 1 < text.Length)
                    {
                        result.Append(text[++i]);
                    }
                    else if (c == '"')
                    {
                        return result.ToString();
                    }
                    else
                    {
                        result.Append(c);
                    }
                }

                throw new FormatException("A text without its closing quote.");
            }
        }
    }
}
